from .base import AbstractDataset
from pathlib import Path
import pickle


class ML60Dataset(AbstractDataset):
    """
    MovieLens-60 dataset for BERT4Rec, loaded from pre-converted dataset.pkl
    (generated by convert_disco_to_bert4rec.py).

    Item IDs are 1-based (1..17188), PAD=0, MASK=17189.
    The dataset.pkl is placed at:
      BERT4Rec/Data/preprocessed/ml60_min_rating0-min_uc0-min_sc0-splitleave_one_out/dataset.pkl
    """

    def __init__(self, args):
        self.args = args

    @classmethod
    def code(cls):
        return 'ml60'

    @classmethod
    def url(cls):
        return ''

    @classmethod
    def is_zipfile(cls):
        return False

    def load_dataset(self):
        dataset_path = self._get_preprocessed_dataset_path()
        assert dataset_path.is_file(), (
            f"Dataset not found at {dataset_path}. "
            f"Run convert_disco_to_bert4rec.py first."
        )
        with dataset_path.open('rb') as f:
            return pickle.load(f)

    def preprocess(self):
        pass

    def load_ratings_df(self):
        raise NotImplementedError

    def _get_preprocessed_folder_path(self):
        root = Path(__file__).parent.parent / 'Data' / 'preprocessed'
        return root / 'ml60_min_rating0-min_uc0-min_sc0-splitleave_one_out'

    def _get_preprocessed_dataset_path(self):
        return self._get_preprocessed_folder_path() / 'dataset.pkl'
